"""Write packaging/requirements-build.lock from a folder of downloaded wheels (developer tool).

    build_exe.ps1 -RefreshLock  runs:
      pip download --only-binary=:all: -r packaging\\requirements-build.txt -d <build root>\\wheels
      python packaging\\lock_requirements.py <build root>\\wheels packaging\\requirements-build.lock

Every wheel (the pins and all their dependencies, such as pefile, altgraph, pywin32-ctypes,
packaging, setuptools and pyinstaller-hooks-contrib) is listed as name==version with its
sha256, so `pip install --require-hashes` refuses anything else.
"""
from __future__ import annotations

import hashlib
import re
import sys
from pathlib import Path

HEADER = """# Generated by packaging/lock_requirements.py from downloaded wheels. Do not edit by hand.
# Install with: pip install --only-binary=:all: --require-hashes -r packaging/requirements-build.lock
"""


def wheel_name_version(filename: str) -> tuple[str, str]:
    match = re.match(r"^(?P<name>[^-]+)-(?P<version>[^-]+)-", filename)
    if not match or not filename.endswith(".whl"):
        raise ValueError(f"not a wheel file name: {filename}")
    return re.sub(r"[-_.]+", "-", match["name"]).lower(), match["version"]


def lock_lines(folder: Path) -> list[str]:
    entries: dict[tuple[str, str], list[str]] = {}
    for path in sorted(Path(folder).glob("*.whl")):
        key = wheel_name_version(path.name)
        entries.setdefault(key, []).append(hashlib.sha256(path.read_bytes()).hexdigest())
    names = [name for name, _ in entries]
    duplicates = sorted({n for n in names if names.count(n) > 1})
    if duplicates:
        raise ValueError("several versions downloaded for: " + ", ".join(duplicates))
    lines = []
    for (name, version), digests in sorted(entries.items()):
        hashes = " ".join(f"--hash=sha256:{d}" for d in sorted(set(digests)))
        lines.append(f"{name}=={version} {hashes}")
    return lines


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    if len(argv) != 2:
        print("usage: lock_requirements.py <wheel folder> <lock file>", file=sys.stderr)
        return 2
    lines = lock_lines(Path(argv[0]))
    if not lines:
        print("no wheels found", file=sys.stderr)
        return 1
    Path(argv[1]).write_text(HEADER + "\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(lines)} pinned wheels to {argv[1]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
